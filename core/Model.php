<?php
/**
 * Model
 * دا الكلاس الأساسي الكل موديلاتنا (User, Photo, Comment) بترث منو
 * غرضو يوفر لينا اتصال قاعدة البيانات جاهز في كل موديل يرث منو
 * بدل ما كل موديل يكتب كود الاتصال براهو
 */

abstract class Model
{
    protected $db;

    /**
     * لما أي موديل يتعمل منو object، الدالة دي بتشتغل أول حاجة
     * وبتجيب اتصال قاعدة البيانات وتحطو في المتغير db
     * عشان الموديل يقدر يستخدمو في أي استعلام SQL
     */
    public function __construct()
    {
        $this->db = Database::getConnection();
    }
}